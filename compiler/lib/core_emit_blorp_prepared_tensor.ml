let emit_literal_inline_struct_write ~emit_expr ctx ~tensor_tmp ~index
    ~struct_ty value =
  let elem_tmp =
    Printf.sprintf "__ten_elem_%d" (Core_emit_context.fresh_temp ctx)
  in
  let value_arg = render_arg ~emit_expr ctx value in
  emit_template ctx "tensor_literal_write_inline_struct"
    [ tensor_tmp; string_of_int index; value_arg; elem_tmp; struct_ty ]

let emit_literal_boxed_write_rendered ctx ~tensor_tmp ~index ~value_arg =
  emit_template ctx "tensor_literal_write_boxed"
    [ tensor_tmp; string_of_int index; value_arg ]

let emit_literal_boxed_write ~emit_boxed ctx ~tensor_tmp ~index value =
  let value_arg = render_arg ~emit_expr:emit_boxed ctx value in
  emit_literal_boxed_write_rendered ctx ~tensor_tmp ~index ~value_arg

let emit_literal_boxed_retain ctx value_arg =
  emit_template ctx "tensor_literal_boxed_retain" [ value_arg ]

let emit_fill_alloc_call ctx loc layout ~first_dim ~total_dim =
  Core_emit_context.emit ctx
    (render_fill_alloc_call layout ~first_dim ~total_dim loc)

let emit_alloc ~emit_expr (ctx : Core_emit_context.t) (e : core) size : unit =
  let layout =
    Core_layout_type.tensor_storage_layout_of_type ~reg:ctx.reg e.ty e.loc
  in
  let requires_release =
    tensor_storage_layout_requires_release_or_error ~phase:Core_error.Emit
      ~loc:e.loc layout
  in
  let result_tmp =
    if requires_release then
      Some
        (Printf.sprintf "__tensor_alloc_%d" (Core_emit_context.fresh_temp ctx))
    else None
  in
  let size_arg = render_arg ~emit_expr ctx size in
  let alloc_expr =
    render_alloc_template (alloc_template_of_layout layout) size_arg
  in
  match result_tmp with
  | Some tmp ->
      emit_template ctx "tensor_alloc_with_release" [ alloc_expr; tmp ]
  | None -> Core_emit_context.emit ctx alloc_expr

let emit_raw_view_decl ~emit_expr (ctx : Core_emit_context.t)
    (binding : tensor_raw_view_binding) : unit =
  let pointer_c_type =
    (Core_layout_type.tensor_raw_scalar_abi binding.trv_kind)
      .tras_pointer_c_type
  in
  let source_arg = render_arg ~emit_expr ctx binding.trv_source in
  emit_template ctx "tensor_raw_view_decl"
    [ pointer_c_type; tensor_view_c_name binding.trv_var; source_arg ]

let emit_raw_read ~emit_expr (ctx : Core_emit_context.t)
    (read : tensor_raw_read) : unit =
  let index_arg = render_arg ~emit_expr ctx read.trr_index in
  emit_template ctx "tensor_raw_read"
    [ tensor_view_c_name read.trr_view; index_arg ]

let emit_raw_write_expr ~emit_expr (ctx : Core_emit_context.t)
    (write : tensor_raw_write) : unit =
  let index_arg = render_arg ~emit_expr ctx write.trw_index in
  let value_arg = render_arg ~emit_expr ctx write.trw_value in
  emit_template ctx "tensor_raw_write_expr"
    [ tensor_view_c_name write.trw_view; index_arg; value_arg ]

let emit_raw_write_stmt ~emit_expr (ctx : Core_emit_context.t)
    (write : tensor_raw_write) : unit =
  let index_arg = render_arg ~emit_expr ctx write.trw_index in
  let value_arg = render_arg ~emit_expr ctx write.trw_value in
  emit_template ctx "tensor_raw_write_stmt"
    [ tensor_view_c_name write.trw_view; index_arg; value_arg ]

let emit_storage_check ~emit_expr ctx template tensor =
  let tensor_arg = render_arg ~emit_expr ctx tensor in
  let vector_tmp =
    Printf.sprintf "__tensor_layout_%d" (Core_emit_context.fresh_temp ctx)
  in
  emit_template ctx
    (storage_check_template_name template)
    [ tensor_arg; vector_tmp ]

let emit_word_storage_check ~emit_expr ctx tensor =
  emit_storage_check ~emit_expr ctx WordStorageCheckTemplate tensor

let emit_f64_storage_check ~emit_expr ctx tensor =
  emit_storage_check ~emit_expr ctx F64StorageCheckTemplate tensor

let emit_f32_storage_check ~emit_expr ctx tensor =
  emit_storage_check ~emit_expr ctx F32StorageCheckTemplate tensor

let emit_i64_storage_check ~emit_expr ctx tensor =
  emit_storage_check ~emit_expr ctx I64StorageCheckTemplate tensor

let emit_data_pointer_get_unchecked ~emit_expr ctx tensor index =
  let tensor_arg = render_arg ~emit_expr ctx tensor in
  let index_arg = render_arg ~emit_expr ctx index in
  emit_template ctx "tensor_data_pointer_get_unchecked"
    [ tensor_arg; index_arg ]

let emit_inline_struct_get_unchecked ~emit_expr ctx tensor index ~struct_ty =
  let tensor_arg = render_arg ~emit_expr ctx tensor in
  let index_arg = render_arg ~emit_expr ctx index in
  let vector_tmp =
    Printf.sprintf "__tgu_vec_%d" (Core_emit_context.fresh_temp ctx)
  in
  let index_tmp =
    Printf.sprintf "__tgu_idx_%d" (Core_emit_context.fresh_temp ctx)
  in
  let out_tmp =
    Printf.sprintf "__tgu_out_%d" (Core_emit_context.fresh_temp ctx)
  in
  let raw_tmp =
    Printf.sprintf "__tgu_raw_%d" (Core_emit_context.fresh_temp ctx)
  in
  emit_template ctx "tensor_inline_struct_get_unchecked"
    [
      tensor_arg; index_arg; vector_tmp; index_tmp; out_tmp; raw_tmp; struct_ty;
    ]

let emit_raw_scalar_get_unchecked ~emit_expr ctx template tensor index =
